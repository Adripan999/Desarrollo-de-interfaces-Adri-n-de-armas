    public void setControlador(Controlador_Facturas controlador) {
        this.controlador = controlador;
        btnAnadirActualizar.addActionListener(e -> controlador.anadirOActualizar());
        btnEditar.addActionListener(e -> controlador.editar());
        btnEliminar.addActionListener(e -> controlador.eliminar());
    }

    public String getAsunto() { return txtAsunto.getText(); }
    public String getCantidad() { return txtCantidad.getText(); }
    public int getDia() { return (Integer) spDia.getValue(); }
    public int getMes() { return (Integer) spMes.getValue(); }
    public int getAnio() { return (Integer) spAnio.getValue(); }
    public String getTipo() { return (String) cmbTipo.getSelectedItem(); }
    public int getSeleccion() { return listaFacturas.getSelectedIndex(); }

    public void cargarFactura(Factura f) {
        txtAsunto.setText(f.getAsunto());
        spDia.setValue(f.getFecha().getDayOfMonth());
        spMes.setValue(f.getFecha().getMonthValue());
        spAnio.setValue(f.getFecha().getYear());
        txtCantidad.setText(String.valueOf(f.getCantidad()));
        cmbTipo.setSelectedItem(f.getTipo());
    }

    public void refrescarLista(List<Factura> facturas) {
        int seleccion = listaFacturas.getSelectedIndex();
        modeloLista.clear();
        for (Factura f : facturas) modeloLista.addElement(f);
        if (seleccion >= 0 && seleccion < modeloLista.size()) listaFacturas.setSelectedIndex(seleccion);
    }

    public Factura getFacturaSeleccionada() {
        return listaFacturas.getSelectedValue();
    }

    public void mensaje(String texto, boolean error) {
        lblMensaje.setText(texto);
        lblMensaje.setForeground(error ? java.awt.Color.RED : new java.awt.Color(0, 120, 0));
    }

    public void limpiarCampos() {
        txtAsunto.setText("");
        txtCantidad.setText("");
        spDia.setValue(1);
        spMes.setValue(1);
        spAnio.setValue(2020);
        cmbTipo.setSelectedIndex(0);
        listaFacturas.clearSelection();
    }

